# Build Jetstream Hangar with the .NET Framework C# compiler.
#   powershell -File build.ps1 [-Version 1.2.3] [-OutDir dist]
# The version (default: the VERSION file) is compiled in; the web UI (web\*) is embedded; catalog.json is copied next
# to the exe as the offline catalogue. secrets.json is never built in: it lives in %APPDATA%\JetstreamHangar.
param([string]$Version = "", [string]$OutDir = "", [switch]$Release)
$here = $PSScriptRoot
if (-not $Version) { $Version = (Get-Content (Join-Path $here "VERSION") -Raw).Trim() }
if (-not $OutDir) { $OutDir = Join-Path $here "dist" }
$csc = "C:\Windows\Microsoft.NET\Framework64\v4.0.30319\csc.exe"
$fw = "C:\Windows\Microsoft.NET\Framework64\v4.0.30319"
New-Item -ItemType Directory -Force $OutDir | Out-Null
$gen = Join-Path $env:TEMP "HangarBuild_$([guid]::NewGuid().ToString('N')).cs"
[IO.File]::WriteAllText($gen, "// generated by build.ps1`nstatic class HangarBuild { public const string Version = `"$Version`"; }`n")
# app icon (white aircraft on a blue tile), sizes 256/48/32/16 as PNG entries in one .ico
Add-Type -AssemblyName System.Drawing
$ico = Join-Path $env:TEMP "JetstreamHangar_$([guid]::NewGuid().ToString('N')).ico"
$sizes = 256, 48, 32, 16; $pngs = @()
foreach ($s in $sizes) {
    $bmp = New-Object Drawing.Bitmap $s, $s; $g = [Drawing.Graphics]::FromImage($bmp); $g.SmoothingMode = 'AntiAlias'
    $r = [Math]::Max(2, $s * 0.2); $path = New-Object Drawing.Drawing2D.GraphicsPath
    $path.AddArc(0, 0, $r, $r, 180, 90); $path.AddArc($s - $r - 1, 0, $r, $r, 270, 90); $path.AddArc($s - $r - 1, $s - $r - 1, $r, $r, 0, 90); $path.AddArc(0, $s - $r - 1, $r, $r, 90, 90); $path.CloseFigure()
    $br = New-Object Drawing.Drawing2D.LinearGradientBrush((New-Object Drawing.Point 0, 0), (New-Object Drawing.Point $s, $s), [Drawing.Color]::FromArgb(255, 47, 129, 247), [Drawing.Color]::FromArgb(255, 11, 61, 145))
    $g.FillPath($br, $path)
    $pts = @(50,6, 55,16, 55,40, 92,58, 92,66, 55,56, 55,78, 68,88, 68,94, 50,89, 32,94, 32,88, 45,78, 45,56, 8,66, 8,58, 45,40, 45,16)
    $pp = for ($i = 0; $i -lt $pts.Count; $i += 2) { New-Object Drawing.PointF ($pts[$i] * $s / 100.0), ($pts[$i + 1] * $s / 100.0) }
    $g.FillPolygon([Drawing.Brushes]::White, [Drawing.PointF[]]$pp); $g.Dispose()
    $ms = New-Object IO.MemoryStream; $bmp.Save($ms, [Drawing.Imaging.ImageFormat]::Png); $pngs += , $ms.ToArray(); $bmp.Dispose()
}
$fs = [IO.File]::Create($ico); $w = New-Object IO.BinaryWriter $fs
$w.Write([uint16]0); $w.Write([uint16]1); $w.Write([uint16]$sizes.Count)
$off = 6 + 16 * $sizes.Count
for ($i = 0; $i -lt $sizes.Count; $i++) { $d = if ($sizes[$i] -ge 256) { 0 } else { $sizes[$i] }; $w.Write([byte]$d); $w.Write([byte]$d); $w.Write([byte]0); $w.Write([byte]0); $w.Write([uint16]1); $w.Write([uint16]32); $w.Write([uint32]$pngs[$i].Length); $w.Write([uint32]$off); $off += $pngs[$i].Length }
foreach ($p in $pngs) { $w.Write($p) }
$w.Close()
$res = Get-ChildItem (Join-Path $here "web") -File | % { "/resource:$($_.FullName),web.$($_.Name)" }
$refs = "System.dll", "System.Core.dll", "System.Drawing.dll", "System.Windows.Forms.dll", "System.Web.Extensions.dll", "$fw\System.IO.Compression.dll", "$fw\System.IO.Compression.FileSystem.dll" | % { "/reference:$_" }
& $csc /nologo /target:winexe /optimize+ "/win32icon:$ico" "/out:$OutDir\JetstreamHangar.exe" $refs $res (Join-Path $here "src\Hangar.cs") $gen
$ok = $LASTEXITCODE -eq 0
Remove-Item $gen, $ico -ErrorAction SilentlyContinue
if (-not $ok) { "BUILD FAILED"; exit 1 }
Copy-Item (Join-Path $here "catalog.json") $OutDir -Force
# developer builds run from dist\ without installing themselves; release builds install on first start
$portable = Join-Path $OutDir "portable.txt"
if ($Release) { Remove-Item $portable -ErrorAction SilentlyContinue } else { Set-Content $portable "Developer build: runs from this folder, does not install itself." }
"built $OutDir\JetstreamHangar.exe ($Version)"
