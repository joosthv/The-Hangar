# Build Jetstream Hangar with the .NET Framework C# compiler.
#   powershell -File build.ps1 [-Version 1.2.3] [-OutDir dist]
# The version (default: the VERSION file) is compiled in; the web UI (web\*) is embedded; catalog.json is copied next
# to the exe as the offline catalogue.
# Navigraph API client: users only sign in (QR code / link), so the app's own client id + secret are compiled into
# release builds from a local JSON file (-NavigraphClient, default %APPDATA%\JetstreamHangar\secrets.json). They are
# never in this repository; in the exe they are XOR-masked (keeps them out of plain-text scans, not a real secret).
param([string]$Version = "", [string]$OutDir = "", [switch]$Release, [string]$NavigraphClient = "")
$here = $PSScriptRoot
if (-not $Version) { $Version = (Get-Content (Join-Path $here "VERSION") -Raw).Trim() }
if (-not $OutDir) { $OutDir = Join-Path $here "dist" }
if (-not $NavigraphClient -and $Release) { $NavigraphClient = Join-Path $env:APPDATA "JetstreamHangar\secrets.json" }
$csc = "C:\Windows\Microsoft.NET\Framework64\v4.0.30319\csc.exe"
$fw = "C:\Windows\Microsoft.NET\Framework64\v4.0.30319"
New-Item -ItemType Directory -Force $OutDir | Out-Null
$ngId = ""; $ngSecret = ""; $ngKey = ""
if ($NavigraphClient) {
    if (-not (Test-Path $NavigraphClient)) { "BUILD FAILED: Navigraph client file not found: $NavigraphClient"; exit 1 }
    $nc = Get-Content $NavigraphClient -Raw | ConvertFrom-Json
    if (-not $nc.navigraphClientId -or -not $nc.navigraphClientSecret) { "BUILD FAILED: $NavigraphClient lacks navigraphClientId / navigraphClientSecret"; exit 1 }
    $key = New-Object byte[] 24; (New-Object Security.Cryptography.RNGCryptoServiceProvider).GetBytes($key)
    $mask = { param($s) $b = [Text.Encoding]::UTF8.GetBytes([string]$s); for ($i = 0; $i -lt $b.Length; $i++) { $b[$i] = $b[$i] -bxor $key[$i % $key.Length] }; [Convert]::ToBase64String($b) }
    $ngId = & $mask $nc.navigraphClientId; $ngSecret = & $mask $nc.navigraphClientSecret; $ngKey = [Convert]::ToBase64String($key)
}
$gen = Join-Path $env:TEMP "HangarBuild_$([guid]::NewGuid().ToString('N')).cs"
[IO.File]::WriteAllText($gen, "// generated by build.ps1`nstatic class HangarBuild { public const string Version = `"$Version`"; public const string NgId = `"$ngId`", NgSecret = `"$ngSecret`", NgKey = `"$ngKey`"; }`n")
# app and tray icon: the Jetstream Virtual compass rose (same geometry as web\logo.svg), sizes 256/48/32/16, PNG entries
Add-Type -AssemblyName System.Drawing
$ico = Join-Path $env:TEMP "JetstreamHangar_$([guid]::NewGuid().ToString('N')).ico"
$rose = @(
    @(0,-1, -0.16,-0.154, 0,0), @(-0.494,-0.494, -0.263,-0.141, -0.167,-0.154, 0,0),
    @(1,0, 0.154,-0.16, 0,0),   @(0.494,-0.494, 0.141,-0.263, 0.154,-0.167, 0,0),
    @(0,1, 0.16,0.154, 0,0),    @(0.494,0.494, 0.263,0.141, 0.167,0.154, 0,0),
    @(-1,0, -0.154,0.16, 0,0),  @(-0.494,0.494, -0.141,0.263, -0.154,0.167, 0,0))
$sizes = 256, 48, 32, 16; $pngs = @()
foreach ($s in $sizes) {
    $bmp = New-Object Drawing.Bitmap $s, $s; $g = [Drawing.Graphics]::FromImage($bmp); $g.SmoothingMode = 'AntiAlias'
    $sc = $s * 0.48; $cx = $s / 2.0
    # small sizes get a faint light edge so the slate rose stays visible on a dark taskbar
    $halo = if ($s -le 32) { New-Object Drawing.Pen ([Drawing.Color]::FromArgb(150, 230, 236, 242)), ([Math]::Max(1.0, $s / 24.0)) } else { $null }
    foreach ($poly in $rose) {
        $pts = for ($i = 0; $i -lt $poly.Count; $i += 2) { New-Object Drawing.PointF ($cx + $poly[$i] * $sc), ($cx + $poly[$i + 1] * $sc) }
        if ($halo) { $g.DrawPolygon($halo, [Drawing.PointF[]]$pts) }
    }
    $fill = New-Object Drawing.SolidBrush ([Drawing.Color]::FromArgb(255, 107, 123, 140))
    foreach ($poly in $rose) {
        $pts = for ($i = 0; $i -lt $poly.Count; $i += 2) { New-Object Drawing.PointF ($cx + $poly[$i] * $sc), ($cx + $poly[$i + 1] * $sc) }
        $g.FillPolygon($fill, [Drawing.PointF[]]$pts)
    }
    $g.Dispose()
    $ms = New-Object IO.MemoryStream; $bmp.Save($ms, [Drawing.Imaging.ImageFormat]::Png); $pngs += , $ms.ToArray(); $bmp.Dispose()
}
$fs = [IO.File]::Create($ico); $w = New-Object IO.BinaryWriter $fs
$w.Write([uint16]0); $w.Write([uint16]1); $w.Write([uint16]$sizes.Count)
$off = 6 + 16 * $sizes.Count
for ($i = 0; $i -lt $sizes.Count; $i++) { $d = if ($sizes[$i] -ge 256) { 0 } else { $sizes[$i] }; $w.Write([byte]$d); $w.Write([byte]$d); $w.Write([byte]0); $w.Write([byte]0); $w.Write([uint16]1); $w.Write([uint16]32); $w.Write([uint32]$pngs[$i].Length); $w.Write([uint32]$off); $off += $pngs[$i].Length }
foreach ($p in $pngs) { $w.Write($p) }
$w.Close()
$res = @(Get-ChildItem (Join-Path $here "web") -File | % { "/resource:$($_.FullName),web.$($_.Name)" })
# SimConnect.dll (Microsoft, MSFS 2024 SDK redistributable) is embedded for the METAR feed; the hangar extracts it to its
# data folder. Release builds refuse to go without it; developer builds warn.
$simConnect = if ($env:MSFS2024_SDK) { Join-Path $env:MSFS2024_SDK "SimConnect SDK\lib\SimConnect.dll" } else { "C:\MSFS 2024 SDK\SimConnect SDK\lib\SimConnect.dll" }
if (Test-Path $simConnect) { $res += "/resource:$simConnect,native.SimConnect.dll" }
elseif ($Release) { "BUILD FAILED: SimConnect.dll not found ($simConnect): install the MSFS 2024 SDK or set MSFS2024_SDK"; exit 1 }
else { "warning: SimConnect.dll not found ($simConnect), built without the METAR sim feed DLL" }
$refs = "System.dll", "System.Core.dll", "System.Drawing.dll", "System.Windows.Forms.dll", "System.Web.Extensions.dll", "System.Security.dll", "System.Management.dll","$fw\System.IO.Compression.dll", "$fw\System.IO.Compression.FileSystem.dll" | % { "/reference:$_" }
& $csc /nologo /target:winexe /optimize+ "/win32icon:$ico" "/out:$OutDir\JetstreamHangar.exe" $refs $res (Get-ChildItem (Join-Path $here "src\*.cs") | % FullName) $gen
$ok = $LASTEXITCODE -eq 0
Remove-Item $gen, $ico -ErrorAction SilentlyContinue
if (-not $ok) { "BUILD FAILED"; exit 1 }
Copy-Item (Join-Path $here "catalog.json") $OutDir -Force
# developer builds run from dist\ without installing themselves; release builds install on first start
$portable = Join-Path $OutDir "portable.txt"
if ($Release) { Remove-Item $portable -ErrorAction SilentlyContinue } else { Set-Content $portable "Developer build: runs from this folder, does not install itself." }
"built $OutDir\JetstreamHangar.exe ($Version)" + $(if ($ngId) { ", Navigraph client built in" } else { "" })
