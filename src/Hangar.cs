// Jetstream Hangar: a small tray app with a local web server (http://localhost:48330) that
//  - shows a catalogue of aircraft (catalog.json on GitHub) and installs, updates and removes them in the MSFS 2024
//    Community folder from GitHub Releases (zip asset per release, optional .sha256 next to it),
//  - is the backend of the in-sim EFBs: Navigraph device-flow requests are forwarded with the client credentials
//    (kept on this computer, not in the aircraft packages), and the aircraft technical state is synced for display.
// Built with the .NET Framework C# compiler (C# 5): see build.ps1. Settings and data: %APPDATA%\JetstreamHangar.
using System;
using System.Collections.Generic;
using System.Diagnostics;
using System.Drawing;
