static class Hangar
{
    public const string AppName = "Jetstream Hangar";
    public static string AppVersion { get { return HangarBuild.Version; } }   // HangarBuild: generated by build.ps1 from VERSION
    // port and data folder can be overridden (automated tests run a second instance next to the real one)
    public static readonly int Port = EnvInt("JETSTREAM_HANGAR_PORT", 48330);
    public static readonly string DataDir = Environment.GetEnvironmentVariable("JETSTREAM_HANGAR_DATA") ?? Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.ApplicationData), "JetstreamHangar");
    static int EnvInt(string k, int def) { int v; return int.TryParse(Environment.GetEnvironmentVariable(k), out v) ? v : def; }
    public static readonly JavaScriptSerializer Json = new JavaScriptSerializer { MaxJsonLength = int.MaxValue };
    static NotifyIcon tray;
    static HttpListener listener;

    // diagnostics: %APPDATA%\JetstreamHangar\hangar.log (unexpected errors, installs, updates)
    public static void Log(string text)
    {
        try
        {
            Directory.CreateDirectory(DataDir);
            string f = Path.Combine(DataDir, "hangar.log");
            if (File.Exists(f) && new FileInfo(f).Length > 1000000) File.Delete(f);
            File.AppendAllText(f, DateTime.Now.ToString("yyyy-MM-dd HH:mm:ss") + "  " + AppVersion + "  " + text + Environment.NewLine);
        }
        catch { }
    }

    [STAThread]
    static void Main(string[] args)
    {
        // never die silently: log anything unexpected (the first release crashed when GitHub was unreachable)
        AppDomain.CurrentDomain.UnhandledException += delegate (object s, UnhandledExceptionEventArgs e) { Log("CRASH " + e.ExceptionObject); };
        Application.SetUnhandledExceptionMode(UnhandledExceptionMode.CatchException);
        Application.ThreadException += delegate (object s, ThreadExceptionEventArgs e) { Log("UI error " + e.Exception); };
        var argl = new List<string>(args);
        if (argl.Contains("--uninstall")) { Installer.Uninstall(argl.Contains("--quiet")); return; }
        // started by a self-update: wait until the previous version has exited, then remove its renamed exe
        bool updated = args.Length >= 2 && args[0] == "--updated";
        if (updated) SelfUpdate.FinishAfterRestart(args[1]);
        // started from a download (not the installed copy): install, start the installed copy, done
        if (!updated && Installer.ShouldInstall(argl) && Installer.InstallAndLaunch(argl)) return;
        bool fresh;
        using (var mutex = new Mutex(true, "JetstreamHangar_SingleInstance_" + Port, out fresh))
        {
            if (!fresh) { OpenUi(); return; }
            ServicePointManager.SecurityProtocol = SecurityProtocolType.Tls12;
            Directory.CreateDirectory(DataDir);
            Settings.Load();
            try
            {
                listener = new HttpListener();
                listener.Prefixes.Add("http://localhost:" + Port + "/");
                listener.Start();
            }
            catch (Exception e)
            {
                MessageBox.Show("Port " + Port + " is in use or blocked:\n" + e.Message, AppName, MessageBoxButtons.OK, MessageBoxIcon.Error);
                return;
            }
            new Thread(ServeLoop) { IsBackground = true }.Start();
            new Thread(UpdateLoop) { IsBackground = true }.Start();

            Application.EnableVisualStyles();
            tray = new NotifyIcon { Icon = AppIcon(), Text = AppName, Visible = true };
            var menu = new ContextMenu();
            menu.MenuItems.Add("Open " + AppName, delegate { OpenUi(); });
            menu.MenuItems.Add("Jetstream Hangar " + AppVersion) .Enabled = false;
            menu.MenuItems.Add("Check for updates", delegate { ThreadPool.QueueUserWorkItem(delegate { CheckEverything(false); }); });
            menu.MenuItems.Add("-");
            menu.MenuItems.Add("Quit", delegate { tray.Visible = false; Application.Exit(); });
            tray.ContextMenu = menu;
            tray.DoubleClick += delegate { OpenUi(); };
            tray.BalloonTipClicked += delegate { OpenUi(); };
            if (Installer.IsInstalled) Installer.RefreshRegistration();
            if (updated) Notify(AppName, "Updated to version " + AppVersion);
            // first start: tell where the app lives (Windows 11 hides new tray icons behind the ^ arrow)
            string marker = Path.Combine(DataDir, "firstrun.done");
            if (!File.Exists(marker))
            {
                Notify(AppName, "Jetstream Hangar runs in the tray (taskbar, hidden icons ^). It starts with Windows and keeps your aircraft up to date.");
                try { File.WriteAllText(marker, AppVersion); } catch { }
            }
            Log("started" + (Installer.IsInstalled ? " (installed)" : " (portable)") + (updated ? " after self-update" : ""));
            if (args.Length == 0) OpenUi();
            else if (Environment.GetEnvironmentVariable("JETSTREAM_HANGAR_DATA") != null) tray.Visible = false;   // test instance: no tray icon
            Application.Run();
            try { listener.Stop(); } catch { }
        }
    }

    static Icon AppIcon()
    {
        try { return Icon.ExtractAssociatedIcon(Assembly.GetExecutingAssembly().Location); } catch { return SystemIcons.Application; }
    }

    public static void OpenUi() { try { Process.Start("http://localhost:" + Port + "/"); } catch { } }

    public static void Notify(string title, string text)
    {
        if (tray == null) return;
        try { tray.BalloonTipTitle = title; tray.BalloonTipText = text; tray.ShowBalloonTip(8000); } catch { }
    }

    // ---------------- update loop: the hangar itself first, then the aircraft ----------------
    // Runs at start and every checkHours. New aircraft releases are installed automatically (setting autoUpdate);
    // while MSFS is running they wait, and the sim is polled every simPollSeconds until it is closed.
    static void UpdateLoop()
    {
        Thread.Sleep(Settings.GetInt("startDelayMs", 3000));
        while (true)
        {
            // one failing check (offline, GitHub down, bad catalogue) must never stop the app: log and try again later
            try
            {
                if (SelfUpdate.CheckAndApply(Settings.GetBool("selfUpdate"))) return;   // the new version takes over (off: only reported)
                CheckUpdates(false);
                if (Settings.GetBool("autoUpdate"))
                {
                    Library.AutoInstall();
                    // aircraft waiting for MSFS to close: poll the sim instead of sleeping for hours
                    while (Library.Waiting.Count > 0)
                    {
                        Thread.Sleep(1000 * Math.Max(1, Settings.GetInt("simPollSeconds", 60)));
                        if (!Community.SimRunning()) Library.AutoInstall();
                    }
                }
            }
            catch (Exception e) { Log("update check failed: " + e.Message); }
            Thread.Sleep(TimeSpan.FromHours(Math.Max(1, Settings.GetInt("checkHours", 6))));
        }
    }
    public static void CheckEverything(bool forceSelf)
    {
        try
        {
            if (SelfUpdate.CheckAndApply(Settings.GetBool("selfUpdate") || forceSelf)) return;   // restarting with the new version
            CheckUpdates(true);
            if (Settings.GetBool("autoUpdate")) Library.AutoInstall();
        }
        catch (Exception e) { Log("check for updates failed: " + e.Message); }
    }
    public static void Quit() { try { if (tray != null) tray.Visible = false; } catch { } try { listener.Stop(); } catch { } Environment.Exit(0); }
    static void CheckUpdates(bool manual)
    {
        try
        {
            var list = Library.List(true);
            var upd = list.Where(a => (bool)a["installed"] && (bool)a["updateAvailable"]).ToList();
            if (upd.Count > 0) Notify("Updates available", string.Join(", ", upd.Select(a => a["name"] + " " + a["latestVersion"]).ToArray()));
            else if (manual) Notify(AppName, "All installed aircraft are up to date.");
        }
        catch (Exception e) { if (manual) Notify(AppName, "Update check failed: " + e.Message); }
    }

    // ---------------- HTTP ----------------
    static void ServeLoop()
    {
        while (listener.IsListening)
        {
            HttpListenerContext ctx;
            try { ctx = listener.GetContext(); } catch { return; }
            ThreadPool.QueueUserWorkItem(delegate { Handle(ctx); });
        }
    }

    static void Handle(HttpListenerContext ctx)
    {
        var req = ctx.Request; var res = ctx.Response;
        try
        {
            string path = req.Url.AbsolutePath;
            if (path.StartsWith("/api/"))
            {
                // the EFB runs in the sim's browser (and tests in a normal browser): allow cross-origin calls
                res.AddHeader("Access-Control-Allow-Origin", "*");
                res.AddHeader("Access-Control-Allow-Headers", "Content-Type");
                res.AddHeader("Access-Control-Allow-Methods", "GET, POST, OPTIONS");
                if (req.HttpMethod == "OPTIONS") { res.StatusCode = 204; res.Close(); return; }
                Api.Route(path, req, res);
                return;
            }
            ServeStatic(path, res);
        }
        catch (Exception e)
        {
            try { Api.Send(res, 500, new Dictionary<string, object> { { "error", e.Message } }); } catch { }
        }
    }

    static void ServeStatic(string path, HttpListenerResponse res)
    {
        if (path == "/") path = "/index.html";
        string name = "web" + path.Replace('/', '.');
        var asm = Assembly.GetExecutingAssembly();
        // a web folder next to the exe overrides the embedded files (handy while developing the UI)
        string disk = Path.Combine(Path.GetDirectoryName(asm.Location), "web" + path.Replace('/', '\\'));
        byte[] data = null;
        if (File.Exists(disk)) data = File.ReadAllBytes(disk);
        else using (var s = asm.GetManifestResourceStream(name)) if (s != null) { var ms = new MemoryStream(); s.CopyTo(ms); data = ms.ToArray(); }
        if (data == null) { res.StatusCode = 404; res.Close(); return; }
        res.ContentType = path.EndsWith(".html") ? "text/html; charset=utf-8" : path.EndsWith(".js") ? "text/javascript; charset=utf-8" : path.EndsWith(".css") ? "text/css; charset=utf-8" : path.EndsWith(".png") ? "image/png" : path.EndsWith(".svg") ? "image/svg+xml" : "application/octet-stream";
        res.AddHeader("Cache-Control", "no-cache");
        res.OutputStream.Write(data, 0, data.Length);
        res.Close();
    }
}

// ---------------- settings (%APPDATA%\JetstreamHangar\settings.json) and secrets (secrets.json) ----------------
static class Settings
{
    // raw.githubusercontent.com is not counted against the GitHub API rate limit (60 requests per hour without a token)
    public const string DefaultCatalog = "https://raw.githubusercontent.com/joosthv/The-Hangar/main/catalog.json";
    const string OldDefaultCatalog = "https://api.github.com/repos/joosthv/The-Hangar/contents/catalog.json";   // 1.0.0 - 1.0.1
    static Dictionary<string, object> s = new Dictionary<string, object>();
    static Dictionary<string, object> secrets = new Dictionary<string, object>();
    static readonly object gate = new object();
    static string File_ { get { return Path.Combine(Hangar.DataDir, "settings.json"); } }
    static string Secrets_ { get { return Path.Combine(Hangar.DataDir, "secrets.json"); } }

    public static void Load()
    {
        lock (gate)
        {
            s = ReadJson(File_) ?? new Dictionary<string, object>();
            secrets = ReadJson(Secrets_) ?? new Dictionary<string, object>();
            // secrets.json may also ship next to the exe (written by the installer / build)
            if (secrets.Count == 0) secrets = ReadJson(Path.Combine(Path.GetDirectoryName(Assembly.GetExecutingAssembly().Location), "secrets.json")) ?? secrets;
            // default catalogue: catalog.json in the The-Hangar repository (contents API: default branch, public or private)
            if (!s.ContainsKey("catalogUrl") || Convert.ToString(s["catalogUrl"]) == OldDefaultCatalog) s["catalogUrl"] = DefaultCatalog;
            if (!s.ContainsKey("checkHours")) s["checkHours"] = 6;
            if (!s.ContainsKey("prerelease")) s["prerelease"] = false;
            if (!s.ContainsKey("autoUpdate")) s["autoUpdate"] = true;     // install new aircraft releases automatically
            if (!s.ContainsKey("selfUpdate")) s["selfUpdate"] = true;     // keep Jetstream Hangar itself up to date
            if (!s.ContainsKey("hangarRepo")) s["hangarRepo"] = "joosthv/The-Hangar";
            if (!s.ContainsKey("navigraphIdentity")) s["navigraphIdentity"] = "https://identity.api.navigraph.com";   // test hook: mock identity server
            if (!s.ContainsKey("airportsUrl")) s["airportsUrl"] = AirportDb.DefaultUrl;                                   // test hook: mock airport list
        }
    }
    public static Dictionary<string, object> ReadJson(string f)
    {
        try { return File.Exists(f) ? Hangar.Json.Deserialize<Dictionary<string, object>>(File.ReadAllText(f)) : null; } catch { return null; }
    }
    public static void Save() { lock (gate) File.WriteAllText(File_, Hangar.Json.Serialize(s)); }
    public static string Get(string k) { lock (gate) { object v; return s.TryGetValue(k, out v) && v != null ? Convert.ToString(v) : ""; } }
    public static int GetInt(string k, int def) { int i; return int.TryParse(Get(k), out i) ? i : def; }
    public static bool GetBool(string k) { return Get(k).ToLowerInvariant() == "true"; }
    public static void Set(string k, object v) { lock (gate) s[k] = v; }
    public static string Secret(string k)
    {
        lock (gate)
        {
            // never trust a single read at start-up: if the credentials are missing, look again (1.0.1 missed them once)
            if (secrets.Count == 0)
            {
                secrets = ReadJson(Secrets_) ?? ReadJson(Path.Combine(Path.GetDirectoryName(Assembly.GetExecutingAssembly().Location), "secrets.json")) ?? new Dictionary<string, object>();
                if (secrets.Count > 0) Hangar.Log("Navigraph credentials loaded on demand");
            }
            object v; if (secrets.TryGetValue(k, out v) && v != null && Convert.ToString(v).Length > 0) return Convert.ToString(v);
            // otherwise the Navigraph client entered on the hangar page (navigraph-client.dat, DPAPI)
            if (client == null) client = ReadClient() ?? new Dictionary<string, object>();
            if (client.TryGetValue(k, out v) && v != null && Convert.ToString(v).Length > 0) return Convert.ToString(v);
            // finally the app's own client compiled into release builds (build.ps1), so users only sign in
            return BuiltIn(k == "navigraphClientId" ? HangarBuild.NgId : k == "navigraphClientSecret" ? HangarBuild.NgSecret : "");
        }
    }
    static string BuiltIn(string masked)
    {
        if (string.IsNullOrEmpty(masked) || string.IsNullOrEmpty(HangarBuild.NgKey)) return "";
        var key = Convert.FromBase64String(HangarBuild.NgKey); var b = Convert.FromBase64String(masked);
        for (int i = 0; i < b.Length; i++) b[i] ^= key[i % key.Length];
        return Encoding.UTF8.GetString(b);
    }
    static Dictionary<string, object> client;
    static string Client_ { get { return Path.Combine(Hangar.DataDir, "navigraph-client.dat"); } }
    static Dictionary<string, object> ReadClient()
    {
        try { return File.Exists(Client_) ? Hangar.Json.Deserialize<Dictionary<string, object>>(Encoding.UTF8.GetString(ProtectedData.Unprotect(File.ReadAllBytes(Client_), null, DataProtectionScope.CurrentUser))) : null; }
        catch (Exception e) { Hangar.Log("navigraph client credentials unreadable: " + e.Message); return null; }
    }
    // Navigraph API client (id + secret from the Navigraph developer portal) entered on the hangar page; empty removes it
    public static string SetNavigraphClient(string id, string secret)
    {
        id = (id ?? "").Trim(); secret = (secret ?? "").Trim();
        lock (gate)
        {
            if (id.Length == 0 && secret.Length == 0) { if (File.Exists(Client_)) File.Delete(Client_); client = new Dictionary<string, object>(); Hangar.Log("navigraph client credentials removed"); return null; }
            if (!Regex.IsMatch(id, "^[A-Za-z0-9._-]{3,100}$") || secret.Length < 8 || secret.Length > 200 || secret.Any(char.IsWhiteSpace)) return "Enter the client ID and the client secret of your Navigraph API client.";
            var d = new Dictionary<string, object> { { "navigraphClientId", id }, { "navigraphClientSecret", secret } };
            File.WriteAllBytes(Client_, ProtectedData.Protect(Encoding.UTF8.GetBytes(Hangar.Json.Serialize(d)), null, DataProtectionScope.CurrentUser));
            client = d;
            Hangar.Log("navigraph client credentials stored");
            return null;
        }
    }
    public static Dictionary<string, object> Public()
    {
        lock (gate)
        {
            var d = new Dictionary<string, object>(s);
            d["githubToken"] = Get("githubToken").Length > 0 ? "set" : "";
            d["communityDetected"] = Community.Detect();
            d["community"] = Community.Path_;
            d["autostart"] = Autostart.Enabled;
            return d;
        }
    }
}

// ---------------- MSFS 2024 Community folder ----------------
static class Community
{
    public static string Path_ { get { var o = Settings.Get("communityOverride"); return o.Length > 0 ? o : Detect(); } }
    // InstalledPackagesPath in UserCfg.opt (Steam and Microsoft Store installs), else the default location
    public static string Detect()
    {
        var appData = Environment.GetFolderPath(Environment.SpecialFolder.ApplicationData);
        var local = Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData);
        var cfgs = new[] {
            Path.Combine(appData, @"Microsoft Flight Simulator 2024\UserCfg.opt"),
            Path.Combine(local, @"Packages\Microsoft.Limitless_8wekyb3d8bbwe\LocalCache\UserCfg.opt"),
        };
        foreach (var c in cfgs)
        {
            try
            {
                if (!File.Exists(c)) continue;
                foreach (var line in File.ReadAllLines(c))
                {
                    var m = Regex.Match(line, "^\\s*InstalledPackagesPath\\s+\"(.+)\"");
                    if (m.Success) { var p = Path.Combine(m.Groups[1].Value, "Community"); if (Directory.Exists(p)) return p; }
                }
            }
            catch { }
        }
        var def = Path.Combine(appData, @"Microsoft Flight Simulator 2024\Packages\Community");
        return Directory.Exists(def) ? def : "";
    }
    // the SDK package tool starts FlightSimulator2024.exe headless ("... BuildAssetPackages ...") to compile packages;
    // that is not the sim being flown, so it does not count (the answer per process id is cached: WMI is slow)
    static readonly Dictionary<int, bool> buildInstance = new Dictionary<int, bool>();
    public static bool SimRunning()
    {
        foreach (var p in Process.GetProcesses())
        {
            try
            {
                if (!p.ProcessName.StartsWith("FlightSimulator", StringComparison.OrdinalIgnoreCase)) continue;
                bool build;
                lock (buildInstance)
                    if (!buildInstance.TryGetValue(p.Id, out build))
                    {
                        build = CommandLine(p.Id).IndexOf("BuildAssetPackages", StringComparison.OrdinalIgnoreCase) >= 0;
                        buildInstance[p.Id] = build;
                    }
                if (!build) return true;
            }
            catch { }
        }
        return false;
    }
    static string CommandLine(int pid)
    {
        try
        {
            using (var s = new System.Management.ManagementObjectSearcher("SELECT CommandLine FROM Win32_Process WHERE ProcessId = " + pid))
                foreach (System.Management.ManagementObject o in s.Get()) return Convert.ToString(o["CommandLine"]) ?? "";
        }
        catch { }
        return "";
    }
    public static string InstalledVersion(string package)
    {
        var dir = Path_; if (dir.Length == 0) return "";
        var m = Settings.ReadJson(Path.Combine(dir, package, "manifest.json"));
        object v; return m != null && m.TryGetValue("package_version", out v) ? Convert.ToString(v) : "";
    }
}

// ---------------- start with Windows (opt-in from the settings page) ----------------
static class Autostart
{
    const string Key = @"Software\Microsoft\Windows\CurrentVersion\Run";
    // value name per installation (tests use their own name so the real entry is never touched)
    static string Name { get { return Installer.RegName == "JetstreamHangar" ? Hangar.AppName : Installer.RegName; } }
    public static bool Enabled
    {
        get { using (var k = Microsoft.Win32.Registry.CurrentUser.OpenSubKey(Key)) return k != null && k.GetValue(Name) != null; }
        set { Set(value, Assembly.GetExecutingAssembly().Location); }
    }
    public static void Set(bool on, string exe)
    {
        using (var k = Microsoft.Win32.Registry.CurrentUser.CreateSubKey(Key))
        {
            if (on) k.SetValue(Name, "\"" + exe + "\" --background");
            else k.DeleteValue(Name, false);
        }
    }
}

// ---------------- GitHub ----------------
static class GitHub
{
    public static HttpWebRequest Request(string url, string accept)
    {
        var r = (HttpWebRequest)WebRequest.Create(url);
        r.UserAgent = Hangar.AppName + "/" + Hangar.AppVersion;
        r.Accept = accept ?? "application/vnd.github+json";
        r.AllowAutoRedirect = true;
        r.Timeout = 30000;
        var token = Settings.Get("githubToken");
        // the token is only sent to the GitHub API itself, never to the download redirect hosts
        string apiBase = Settings.Get("githubApiBase");
        if (token.Length > 0 && (url.StartsWith("https://api.github.com/") || (apiBase.Length > 0 && url.StartsWith(apiBase.TrimEnd('/') + "/")))) r.Headers["Authorization"] = "Bearer " + token;
        return r;
    }
    // release asset download: private repositories need the asset API URL with the token; GitHub answers with a redirect
    // to its file storage, which is followed without the token (the storage host must never see it)
    public static HttpWebResponse OpenAsset(Dictionary<string, object> rel, string browserKey, string apiKey)
    {
        object apiUrl; string url = Convert.ToString(rel[browserKey]);
        if (Settings.Get("githubToken").Length > 0 && rel.TryGetValue(apiKey, out apiUrl) && apiUrl != null)
        {
            var r = Request(Convert.ToString(apiUrl), "application/octet-stream");
            r.AllowAutoRedirect = false;
            var resp = (HttpWebResponse)r.GetResponse();
            if ((int)resp.StatusCode >= 300 && (int)resp.StatusCode < 400) { url = resp.Headers["Location"]; resp.Close(); }
            else return resp;
        }
        var plain = Request(url, "application/octet-stream");
        return (HttpWebResponse)plain.GetResponse();
    }
    // Every answer is kept in DataDir\cache with its ETag: repeated checks are conditional requests (304 = unchanged), and
    // when GitHub refuses (rate limit) or cannot be reached the last known answer is used and a notice is shown.
    static readonly Dictionary<string, string> notices = new Dictionary<string, string>();
    public static string Notice { get { lock (notices) return string.Join(" ", notices.Values.Distinct().ToArray()); } }
    static string CacheFile(string url)
    {
        var dir = Path.Combine(Hangar.DataDir, "cache"); Directory.CreateDirectory(dir);
        using (var sha = SHA1.Create()) return Path.Combine(dir, BitConverter.ToString(sha.ComputeHash(Encoding.UTF8.GetBytes(url))).Replace("-", "").ToLowerInvariant() + ".json");
    }
    public static string GetText(string url)
    {
        var cf = CacheFile(url); var cached = Settings.ReadJson(cf);
        string cachedBody = cached != null && cached.ContainsKey("body") ? Convert.ToString(cached["body"]) : null;
        // the contents API returns the file itself with the raw media type
        var r = Request(url, url.Contains("/contents/") ? "application/vnd.github.raw" : null);
        if (cachedBody != null && cached.ContainsKey("etag") && Convert.ToString(cached["etag"]).Length > 0) r.Headers["If-None-Match"] = Convert.ToString(cached["etag"]);
        try
        {
            using (var resp = (HttpWebResponse)r.GetResponse())
            {
                lock (notices) notices.Remove(url);
                if (resp.StatusCode == HttpStatusCode.NotModified && cachedBody != null) return cachedBody;
                string body; using (var sr = new StreamReader(resp.GetResponseStream(), Encoding.UTF8)) body = sr.ReadToEnd();
                try { File.WriteAllText(cf, Hangar.Json.Serialize(new Dictionary<string, object> { { "url", url }, { "etag", resp.Headers["ETag"] ?? "" }, { "body", body } })); } catch { }
                return body;
            }
        }
        catch (WebException e)
        {
            var hr = e.Response as HttpWebResponse;
            if (hr != null && hr.StatusCode == HttpStatusCode.NotModified && cachedBody != null) { lock (notices) notices.Remove(url); return cachedBody; }
            string why = Describe(e);
            if (hr != null && hr.StatusCode == HttpStatusCode.NotFound) throw new Exception(why);   // gone: never show stale data
            if (cachedBody == null) throw new Exception(why);
            Hangar.Log("GitHub: " + why + " - using the cached answer for " + url);
            lock (notices) notices[url] = why + " Showing the last known versions.";
            return cachedBody;
        }
    }
    static string Describe(WebException e)
    {
        var hr = e.Response as HttpWebResponse;
        if (hr == null) return "GitHub could not be reached (" + e.Message + ").";
        int code = (int)hr.StatusCode;
        if ((code == 403 || code == 429) && (hr.Headers["X-RateLimit-Remaining"] == "0" || hr.Headers["Retry-After"] != null))
        {
            long reset; string when = "";
            if (long.TryParse(hr.Headers["X-RateLimit-Reset"], out reset)) when = " until " + new DateTime(1970, 1, 1, 0, 0, 0, DateTimeKind.Utc).AddSeconds(reset).ToLocalTime().ToString("HH:mm");
            return "GitHub rate limit reached" + when + (Settings.Get("githubToken").Length > 0 ? "." : " (60 requests per hour without a token; a GitHub token under Settings raises it).");
        }
        return "GitHub answered " + code + " " + hr.StatusDescription + ".";
    }
    // newest release whose tag starts with the aircraft's prefix and that carries its zip asset
    public static Dictionary<string, object> LatestRelease(string repo, string tagPrefix, string assetPrefix) { return LatestRelease(repo, tagPrefix, assetPrefix, ".zip"); }
    public static Dictionary<string, object> LatestRelease(string repo, string tagPrefix, string assetPrefix, string ext)
    {
        // the API base can be pointed at a mock server for the automated tests (setting githubApiBase)
        string apiBase = Settings.Get("githubApiBase").Length > 0 ? Settings.Get("githubApiBase").TrimEnd('/') : "https://api.github.com";
        var list = Library.Arr(Hangar.Json.DeserializeObject(GetText(apiBase + "/repos/" + repo + "/releases?per_page=50")));
        bool pre = Settings.GetBool("prerelease");
        Dictionary<string, object> best = null; Version bestV = null;
        foreach (var r in list)
        {
            if ((bool)r["draft"] || ((bool)r["prerelease"] && !pre)) continue;
            string tag = Convert.ToString(r["tag_name"]);
            if (tagPrefix.Length > 0 && !tag.StartsWith(tagPrefix, StringComparison.OrdinalIgnoreCase)) continue;
            var asset = Library.Arr(r["assets"]).FirstOrDefault(a => { var n = Convert.ToString(a["name"]); return n.StartsWith(assetPrefix, StringComparison.OrdinalIgnoreCase) && n.EndsWith(ext, StringComparison.OrdinalIgnoreCase); });
            if (asset == null) continue;
            var v = Library.ParseVersion(tag.Substring(tagPrefix.Length));
            if (best == null || (v != null && (bestV == null || v > bestV)))
            {
                var sha = Library.Arr(r["assets"]).FirstOrDefault(a => Convert.ToString(a["name"]) == Convert.ToString(asset["name"]) + ".sha256");
                best = new Dictionary<string, object> {
                    { "version", tag.Substring(tagPrefix.Length).TrimStart('v', 'V') }, { "tag", tag }, { "name", r["name"] }, { "notes", r["body"] ?? "" },
                    { "published", r["published_at"] }, { "url", asset["browser_download_url"] }, { "apiUrl", asset.ContainsKey("url") ? asset["url"] : null }, { "size", asset["size"] },
                    { "shaApiUrl", sha != null && sha.ContainsKey("url") ? sha["url"] : null },
                    { "sha256Url", sha != null ? sha["browser_download_url"] : null },
                };
                bestV = v;
            }
        }
        return best;
    }
}

// ---------------- catalogue, install, update, uninstall ----------------
static class Library
{
    static readonly object gate = new object();
    static Dictionary<string, object> catalog;
    static DateTime catalogAt = DateTime.MinValue;
    static readonly Dictionary<string, Dictionary<string, object>> latest = new Dictionary<string, Dictionary<string, object>>();
    static readonly Dictionary<string, string> latestErr = new Dictionary<string, string>();
    static readonly Dictionary<string, DateTime> latestAt = new Dictionary<string, DateTime>();
    public static Dictionary<string, object> Job = new Dictionary<string, object> { { "state", "idle" } };

    public static List<Dictionary<string, object>> Arr(object o)
    {
        var e = o as System.Collections.IEnumerable;
        return e == null || o is string ? new List<Dictionary<string, object>>() : e.Cast<object>().OfType<Dictionary<string, object>>().ToList();
    }

    public static Version ParseVersion(string s)
    {
        var m = Regex.Match(s ?? "", "(\\d+)(\\.\\d+){0,3}");
        Version v; return m.Success && Version.TryParse(m.Value.Contains(".") ? m.Value : m.Value + ".0", out v) ? v : null;
    }

    // catalog.json from the configured URL; a catalog.json next to the exe is used when no URL is set (offline / dev)
    public static Dictionary<string, object> Catalog(bool refresh)
    {
        lock (gate)
        {
            if (catalog != null && !refresh && DateTime.UtcNow - catalogAt < TimeSpan.FromMinutes(10)) return catalog;
            string url = Settings.Get("catalogUrl"), text = null;
            if (url.Length > 0) text = GitHub.GetText(url);
            else
            {
                var local = Path.Combine(Path.GetDirectoryName(Assembly.GetExecutingAssembly().Location), "catalog.json");
                if (File.Exists(local)) text = File.ReadAllText(local);
            }
            catalog = text != null ? Hangar.Json.Deserialize<Dictionary<string, object>>(text) : new Dictionary<string, object> { { "aircraft", new object[0] } };
            catalogAt = DateTime.UtcNow;
            return catalog;
        }
    }

    static string S(Dictionary<string, object> d, string k) { object v; return d.TryGetValue(k, out v) && v != null ? Convert.ToString(v) : ""; }

    public static List<Dictionary<string, object>> List(bool refresh)
    {
        var cat = Catalog(refresh);
        var outList = new List<Dictionary<string, object>>();
        object arr; if (!cat.TryGetValue("aircraft", out arr) || arr == null) return outList;
        foreach (var a in Arr(arr))
        {
            string id = S(a, "id"), pkg = S(a, "package");
            Dictionary<string, object> rel = null; string err = null; bool stale;
            string inst = Community.InstalledVersion(pkg);
            TimeSpan age;
            lock (gate)
            {
                if (!refresh && latest.ContainsKey(id)) rel = latest[id]; if (!refresh && latestErr.ContainsKey(id)) err = latestErr[id];
                age = latestAt.ContainsKey(id) ? DateTime.UtcNow - latestAt[id] : TimeSpan.MaxValue;
            }
            // the release list is re-read after 10 minutes (cheap: ETag), and after a minute when the installed version is
            // newer than the remembered latest one (a release appeared since: "installed 1.1.0, latest 1.0.0")
            int maxAge = Settings.GetInt("releaseCacheSeconds", 600);   // test hook
            stale = age > TimeSpan.FromSeconds(maxAge);
            var iv0 = ParseVersion(inst); var lv0 = rel != null ? ParseVersion(S(rel, "version")) : null;
            if (iv0 != null && lv0 != null && iv0 > lv0 && age > TimeSpan.FromSeconds(Math.Min(60, maxAge))) stale = true;
            if (refresh || stale || (rel == null && err == null))
            {
                try { rel = GitHub.LatestRelease(S(a, "github"), S(a, "tagPrefix"), S(a, "assetPrefix").Length > 0 ? S(a, "assetPrefix") : pkg); err = rel == null ? "No release published yet" : null; }
                catch (Exception e) { err = "GitHub: " + e.Message; }
                lock (gate) { latest[id] = rel; latestErr[id] = err; latestAt[id] = DateTime.UtcNow; }
            }
            var lv = rel != null ? ParseVersion(S(rel, "version")) : null; var iv = ParseVersion(inst);
            var item = new Dictionary<string, object>(a);
            item["installed"] = inst.Length > 0;
            item["installedVersion"] = inst;
            item["latestVersion"] = rel != null ? S(rel, "version") : "";
            item["release"] = rel;
            item["releaseError"] = err;
            item["updateAvailable"] = inst.Length > 0 && lv != null && (iv == null || lv > iv);
            item["state"] = Sync.Get(id);
            outList.Add(item);
        }
        return outList;
    }

    static void SetJob(string id, string state, double pct, string msg)
    {
        lock (gate) Job = new Dictionary<string, object> { { "id", id }, { "state", state }, { "percent", Math.Round(pct, 1) }, { "message", msg } };
    }

    public static readonly List<string> Waiting = new List<string>();   // aircraft whose update waits for MSFS to close
    public static void AutoInstall()
    {
        List<Dictionary<string, object>> list;
        try { list = List(false); } catch (Exception e) { Hangar.Log("auto-update: catalogue not available: " + e.Message); lock (gate) Waiting.Clear(); return; }
        var upd = list.Where(a => (bool)a["installed"] && (bool)a["updateAvailable"]).ToList();
        lock (gate) Waiting.Clear();
        foreach (var a in upd)
        {
            if (Community.SimRunning())
            {
                lock (gate) Waiting.Add(S(a, "name"));
                continue;
            }
            var err = StartInstall(S(a, "id"), true);
            if (err != null) Hangar.Notify(Hangar.AppName, "Automatic update of " + S(a, "name") + " failed: " + err);
            else if (S(Job, "state") == "error") Hangar.Notify(Hangar.AppName, "Automatic update of " + S(a, "name") + " failed: " + S(Job, "message"));
        }
        if (Waiting.Count > 0) Hangar.Notify("Update waiting", string.Join(", ", Waiting.ToArray()) + ": installs when Microsoft Flight Simulator is closed");
    }

    public static string StartInstall(string id) { return StartInstall(id, false); }
    public static string StartInstall(string id, bool wait)
    {
        lock (gate) if (S(Job, "state") == "running") return "Another installation is running";
        var a = List(false).FirstOrDefault(x => S(x, "id") == id);
        if (a == null) return "Unknown aircraft";
        var rel = a["release"] as Dictionary<string, object>;
        if (rel == null) return "No release available: " + S(a, "releaseError");
        if (Community.Path_.Length == 0) return "Community folder not found - set it in Settings";
        if (Community.SimRunning()) return "Close Microsoft Flight Simulator before installing or updating";
        SetJob(id, "running", 0, "Starting");
        if (wait) Install(a, rel);
        else new Thread(delegate () { Install(a, rel); }) { IsBackground = true }.Start();
        return null;
    }

    static void Install(Dictionary<string, object> a, Dictionary<string, object> rel)
    {
        string id = S(a, "id"), pkg = S(a, "package"), community = Community.Path_;
        string work = Path.Combine(Path.GetTempPath(), "JetstreamHangar", id);
        string tmpDir = Path.Combine(community, ".hangar_new_" + pkg), oldDir = Path.Combine(community, ".hangar_old_" + pkg), target = Path.Combine(community, pkg);
        try
        {
            if (Directory.Exists(work)) Directory.Delete(work, true);
            Directory.CreateDirectory(work);
            string zip = Path.Combine(work, "package.zip");
            // download with progress
            using (var resp = GitHub.OpenAsset(rel, "url", "apiUrl"))
            using (var src = resp.GetResponseStream())
            using (var dst = File.Create(zip))
            {
                long total = resp.ContentLength > 0 ? resp.ContentLength : Convert.ToInt64(rel["size"]), done = 0;
                var buf = new byte[1 << 16]; int n;
                while ((n = src.Read(buf, 0, buf.Length)) > 0)
                {
                    dst.Write(buf, 0, n); done += n;
                    SetJob(id, "running", total > 0 ? 80.0 * done / total : 0, "Downloading " + (done >> 20) + " / " + (total >> 20) + " MB");
                }
            }
            // checksum, when the release has one
            if (rel["sha256Url"] != null)
            {
                SetJob(id, "running", 81, "Verifying");
                string want;
                using (var r = GitHub.OpenAsset(rel, "sha256Url", "shaApiUrl")) using (var sr = new StreamReader(r.GetResponseStream())) want = sr.ReadToEnd().Trim().Split(' ', '\t')[0].ToLowerInvariant();
                string got;
                using (var f = File.OpenRead(zip)) using (var sha = SHA256.Create()) got = BitConverter.ToString(sha.ComputeHash(f)).Replace("-", "").ToLowerInvariant();
                if (got != want) throw new Exception("Checksum mismatch - download corrupted, nothing was changed");
            }
            if (Community.SimRunning()) throw new Exception("Microsoft Flight Simulator was started - close it and try again");
            // unpack next to the target, then swap folders (rollback on failure)
            SetJob(id, "running", 85, "Unpacking");
            if (Directory.Exists(tmpDir)) Directory.Delete(tmpDir, true);
            string unpack = Path.Combine(work, "x");
            ZipFile.ExtractToDirectory(zip, unpack);
            string root = File.Exists(Path.Combine(unpack, "manifest.json")) ? unpack : Path.Combine(unpack, pkg);
            if (!File.Exists(Path.Combine(root, "manifest.json")))
            {
                var dirs = Directory.GetDirectories(unpack);
                if (dirs.Length == 1 && File.Exists(Path.Combine(dirs[0], "manifest.json"))) root = dirs[0];
                else throw new Exception("The release zip does not contain the package (" + pkg + "/manifest.json)");
            }
            SetJob(id, "running", 92, "Installing");
            Directory.Move(root, tmpDir);
            if (Directory.Exists(oldDir)) Directory.Delete(oldDir, true);
            if (Directory.Exists(target)) Directory.Move(target, oldDir);
            try { Directory.Move(tmpDir, target); }
            catch { if (Directory.Exists(oldDir) && !Directory.Exists(target)) Directory.Move(oldDir, target); throw; }
            if (Directory.Exists(oldDir)) Directory.Delete(oldDir, true);
            Directory.Delete(work, true);
            SetJob(id, "done", 100, S(a, "name") + " " + S(rel, "version") + " installed");
            Hangar.Notify(Hangar.AppName, S(a, "name") + " " + S(rel, "version") + " installed");
        }
        catch (Exception e)
        {
            try { if (Directory.Exists(tmpDir)) Directory.Delete(tmpDir, true); } catch { }
            SetJob(id, "error", 0, e.Message);
        }
    }

    public static string Uninstall(string id)
    {
        var a = List(false).FirstOrDefault(x => S(x, "id") == id);
        if (a == null) return "Unknown aircraft";
        if (Community.SimRunning()) return "Close Microsoft Flight Simulator first";
        var dir = Path.Combine(Community.Path_, S(a, "package"));
        if (!Directory.Exists(dir)) return "Not installed";
        // only remove folders that really are this package
        var m = Settings.ReadJson(Path.Combine(dir, "manifest.json"));
        if (m == null) return "Folder has no manifest.json - not removed";
        Directory.Delete(dir, true);
        return null;
    }
}

